// Generate the full English Google Fonts catalogue for FontStory.
// Fetches the public google-webfonts-helper list, keeps the families
// with a latin subset (usable for English text), drops the icon /
// symbol / music faces (no Latin letter glyphs — their cards would
// render blank), and writes two files from the same data so the
// front-end and the back-end can never drift apart:
//   web/google-fonts.js        -> const GOOGLE_FONTS (front-end picker)
//   tgcloud/lib/google-fonts.js -> export const GOOGLE_FONT_IDS (back-end allow-list)
// Run: node scripts/gen-google-fonts.mjs
// The css2 `css` param and `weights` mirror the 12 hand-written
// English entries they replace (family=X or family=X:wght@400;700;900).
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE = 'https://gwfh.mranftl.com/api/fonts';

// Faces with a latin subset but no Latin letter glyphs — icon fonts,
// symbol fonts and musical notation. Their cards would show tofu.
const EXCLUDE = new Set([
  'Material Icons', 'Material Icons Outlined', 'Material Icons Round',
  'Material Icons Sharp', 'Material Icons Two Tone',
  'Material Symbols', 'Material Symbols Outlined', 'Material Symbols Rounded',
  'Material Symbols Sharp',
  'Noto Sans Symbols', 'Noto Sans Symbols 2',
  'Noto Music', 'Noto Znamenny Musical Notation',
]);

const GENERIC = {
  'sans-serif': 'sans-serif',
  'serif': 'serif',
  'display': 'sans-serif',
  'handwriting': 'cursive',
  'monospace': 'monospace',
};
const WANTED = [400, 700, 900];

function slug(family) {
  return family.replace(/[^A-Za-z0-9]/g, '');
}
function cssParam(family, weights, italicOnly) {
  const name = encodeURIComponent(family).replace(/%20/g, '+');
  if (italicOnly) return `family=${name}:ital,wght@1,${weights[0]}`;
  if (weights.length === 1 && weights[0] === 400) return `family=${name}`;
  return `family=${name}:wght@${weights.join(';')}`;
}

const res = await fetch(SOURCE);
if (!res.ok) throw new Error(`fetch ${SOURCE} failed: ${res.status}`);
const all = await res.json();
// Order: Google Fonts popularity (the API's `popularity` rank, 1 =
// most popular) — the fonts people actually want sit in the first
// batches of the infinite scroll, instead of an A-Z list where
// Roboto hides 1,500 cards in.
const latin = all
  .filter((f) => (f.subsets || []).includes('latin') && !EXCLUDE.has(f.family))
  .sort((a, b) => (a.popularity ?? 99999) - (b.popularity ?? 99999));

// Families already built in as Persian fonts (web/app.js FONTS, before
// ...GOOGLE_FONTS) keep their own entries — same id, correct lang and
// eager loading — so they are dropped from the Google list instead of
// shadowing/duplicating them.
import { readFileSync } from 'node:fs';
const appJs = readFileSync(join(root, 'web', 'app.js'), 'utf8');
const fontsBlock = appJs.slice(appJs.indexOf('const FONTS = ['), appJs.indexOf('...GOOGLE_FONTS'));
const builtInIds = new Set([...fontsBlock.matchAll(/\{\s*id: '([^']+)'/g)].map((m) => m[1]));

const seen = new Set();
const entries = [];
const excluded = [];
for (const f of latin) {
  if (EXCLUDE.has(f.family)) { excluded.push(f.family); continue; }
  const id = slug(f.family);
  if (!id || seen.has(id)) { console.warn('SKIP (bad/duplicate id):', f.family); continue; }
  if (builtInIds.has(id)) { excluded.push(f.family + ' (built-in Persian)'); continue; }
  seen.add(id);
  // Upright numeric weights ('regular' is 400); italics excluded.
  const upright = new Set();
  for (const v of f.variants || []) {
    if (v === 'regular') upright.add(400);
    else if (/^\d+$/.test(v)) upright.add(Number(v));
  }
  let weights, italicOnly = false;
  const picked = WANTED.filter((w) => upright.has(w));
  if (picked.length) weights = picked;
  else if (upright.size) weights = [Math.min(...upright)];
  else {
    // Italic-only face (e.g. Molle): load its italic 400.
    italicOnly = true;
    weights = [400];
  }
  const generic = GENERIC[f.category] || 'sans-serif';
  entries.push({
    id,
    label: f.family,
    family: `'${f.family.replace(/'/g, "\\'")}', ${generic}`,
    gname: f.family,
    css: cssParam(f.family, weights, italicOnly),
    weights,
  });
}

const front = `// Generated by scripts/gen-google-fonts.mjs from ${SOURCE} — do not edit by hand.
// ${entries.length} families with a latin subset (English fonts), in
// Google Fonts popularity order (most popular first).
// Icon / symbol / music faces are excluded (no Latin letter glyphs).
const GOOGLE_FONTS = [
${entries.map((e) => `  { id: '${e.id}', label: '${e.label.replace(/'/g, "\\'")}', family: "${e.family}", lang: 'en', lazy: true, gname: '${e.gname.replace(/'/g, "\\'")}', css: '${e.css}', weights: [${e.weights.join(', ')}], sample: 'Your text' },`).join('\n')}
];
`;
writeFileSync(join(root, 'web', 'google-fonts.js'), front);

const back = `// Generated by scripts/gen-google-fonts.mjs from ${SOURCE} — do not edit by hand.
// The ids of the ${entries.length} English Google Fonts in web/google-fonts.js.
// saveDesign.js spreads these into ALLOWED_FONTS.
export const GOOGLE_FONT_IDS = [
${entries.map((e) => `  '${e.id}',`).join('\n')}
];
`;
writeFileSync(join(root, 'tgcloud', 'lib', 'google-fonts.js'), back);

console.log(`families: ${entries.length} (latin ${latin.length}, excluded ${excluded.length}: ${excluded.join(', ')})`);
console.log('wrote web/google-fonts.js + tgcloud/lib/google-fonts.js');
