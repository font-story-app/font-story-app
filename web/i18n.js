// The app's current language (default Persian). setAppLang is called
// once at load (from ?lang=, localStorage, or Telegram's language)
// and again when the register endpoint returns the stored choice.
const APP_LANGS = ['en', 'fa', 'zh', 'ar', 'ru'];
let appLang = 'fa';

function normalizeAppLang(code) {
  return APP_LANGS.includes(code) ? code : 'fa';
}

function setAppLang(code) {
  appLang = normalizeAppLang(code);
  document.documentElement.lang = appLang;
}

// Translate a Persian string; Persian returns the input, and any
// string missing from a language falls back to Persian (never blank).
function tr(s) {
  if (appLang === 'fa') return s;
  return (I18N[appLang] && I18N[appLang][s]) || s;
}

// Where the language comes from, in order: a ?lang= URL parameter
// (also handy for testing), the last saved choice, Telegram's own
// language_code, then Persian.
function detectLang() {
  try {
    const q = new URLSearchParams(location.search).get('lang');
    if (q && APP_LANGS.includes(q)) return q;
    const saved = localStorage.getItem('fontstory:lang');
    if (saved && APP_LANGS.includes(saved)) return saved;
    const tg = window.Telegram && window.Telegram.WebApp && window.Telegram.WebApp.initDataUnsafe && window.Telegram.WebApp.initDataUnsafe.user && window.Telegram.WebApp.initDataUnsafe.user.language_code;
    if (tg) {
      const base = String(tg).split('-')[0];
      if (APP_LANGS.includes(base)) return base;
    }
  } catch (e) { /* storage or Telegram unavailable — fall through */ }
  return 'fa';
}

function saveLang(code) {
  try { localStorage.setItem('fontstory:lang', normalizeAppLang(code)); } catch (e) { /* private mode — ignore */ }
}

// Replace an element's first non-empty text node (labels that share
// the element with an icon or a button keep their siblings).
function setTextNode(el, str) {
  for (const n of el.childNodes) {
    if (n.nodeType === 3 && n.textContent.trim()) { n.textContent = str; return; }
  }
  // No direct text: the label lives inside a child element (the tab
  // buttons keep their icon + a <span> label). Replace the first
  // non-empty text node in the subtree, skipping icon content (svg,
  // .icon, .icon-text) so the icons survive — the old fallback
  // (el.textContent = str) wiped the whole button, icons included.
  const walker = document.createTreeWalker(el, NodeFilter.SHOW_TEXT);
  let n;
  while ((n = walker.nextNode())) {
    const p = n.parentElement;
    if (p && (p.closest('svg') || p.classList.contains('icon') || p.classList.contains('icon-text'))) continue;
    if (n.textContent.trim()) { n.textContent = str; return; }
  }
  el.textContent = str;
}

// Numbers in the UI: Persian digits in fa, Latin digits elsewhere
// (the size readout under the size rail, e.g. 110 vs ۱۱۰).
function fmtNum(n) {
  const s = String(n);
  return appLang === 'fa' ? s.replace(/[0-9]/g, (d) => '۰۱۲۳۴۵۶۷۸۹'[+d]) : s;
}

// Apply the current language to every static string in the page:
// data-i18n for text, data-i18n-ph for placeholders,
// data-i18n-title for titles, data-i18n-aria for aria-labels.
function applyI18n() {
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    setTextNode(el, tr(el.dataset.i18n));
  });
  document.querySelectorAll('[data-i18n-ph]').forEach((el) => {
    el.placeholder = tr(el.dataset.i18nPh);
    // The search placeholder keeps its invisible RLM (U+200F) in
    // Persian so the ellipsis stays on the right side.
    if (appLang === 'fa' && el.dataset.i18nPh === 'جستجوی فونت…') el.placeholder += '\u200F';
  });
  document.querySelectorAll('[data-i18n-title]').forEach((el) => {
    el.title = tr(el.dataset.i18nTitle);
  });
  document.querySelectorAll('[data-i18n-aria]').forEach((el) => {
    el.setAttribute('aria-label', tr(el.dataset.i18nAria));
  });
  document.querySelectorAll('[data-i18n-alt]').forEach((el) => {
    el.alt = tr(el.dataset.i18nAlt);
  });
  // The browser tab title: Persian brand in fa, plain FontStory elsewhere.
  document.title = appLang === 'fa' ? 'FontStory — فونت استوری' : 'FontStory';
}
